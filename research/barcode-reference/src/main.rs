//! Writes `crates/burnburn-generators/tests/fixtures/barcode-bwipp.txt` to stdout.
//!
//! Run: `cd research/barcode-reference && cargo run --release --bin barcode-reference > ../../crates/burnburn-generators/tests/fixtures/barcode-bwipp.txt`
//!
//! The encoder is `bwipp-rs` 0.1.1 (port of Barcode Writer in Pure PostScript), independent of the
//! `anyd` encoder used by BurnBurn. Format, one block per case:
//!
//! ```text
//! case <stable symbology name> <option>=<value>... <payload as hex bytes>
//! L <bar> <space> <bar> ...      linear: element widths as BWIPP draws them (bar first)
//! or one line of '0'/'1' per row  matrix/stacked: BWIPP rows (no quiet zone)
//! end
//! ```
//! PDF417 row heights are not part of the fixture (BWIPP emits one line per codeword row).

use bwipp::{Encoded, Options, Symbology};

struct Case {
    name: &'static str,
    sym: Symbology,
    opts: Vec<(&'static str, &'static str)>,
    payload: &'static str,
}

fn hex(s: &str) -> String {
    s.bytes().map(|b| format!("{b:02x}")).collect()
}

fn main() {
    let mut cases: Vec<Case> = Vec::new();
    for payload in ["0123456789", "1234", "9876", "00", "5"] {
        cases.push(Case { name: "two_of_five_industrial", sym: Symbology::Code2of5, opts: vec![], payload });
        cases.push(Case { name: "two_of_five_iata", sym: Symbology::Iata2of5, opts: vec![], payload });
    }
    for payload in ["0123", "ABCDEF", "1A2B3C", "DEADBEEF", "7", "00FF"] {
        cases.push(Case { name: "plessey", sym: Symbology::Plessey, opts: vec![], payload });
    }
    for (payload, level, cols) in [
        ("1234567890123456", "2", "4"),
        ("1234567890123456", "0", "2"),
        ("98765432101234567890", "4", "3"),
        ("0000000000000", "2", "2"),
    ] {
        cases.push(Case {
            name: "pdf417_compact",
            sym: Symbology::Pdf417Truncated,
            opts: vec![("eclevel", level), ("columns", cols)],
            payload,
        });
        cases.push(Case {
            name: "pdf417",
            sym: Symbology::Pdf417,
            opts: vec![("eclevel", level), ("columns", cols)],
            payload,
        });
    }
    for payload in ["1234567890", "12345678901234567890123456789", "0123456789012345", "HELLO"] {
        cases.push(Case { name: "pdf417_micro", sym: Symbology::MicroPdf417, opts: vec![], payload });
    }

    println!("# Reference modules from bwipp-rs 0.1.1 (port of BWIPP), generated by research/barcode-reference.");
    println!("# Independent of the anyd encoder; see docs/dev-notes/IM22.md (W2-L5d).");
    for c in cases {
        let mut o = Options::default();
        for (k, v) in &c.opts {
            o = o.with(*k, *v);
        }
        let opts: String = c.opts.iter().map(|(k, v)| format!("{k}={v} ")).collect();
        match c.sym.encode(c.payload, &o) {
            Ok(Encoded::Linear(l)) => {
                println!("case {} {}{}", c.name, opts, hex(c.payload));
                let w: Vec<String> = l.bars.iter().map(|b| b.to_string()).collect();
                println!("L {}", w.join(" "));
                println!("end");
            }
            Ok(Encoded::Matrix(m)) => {
                println!("case {} {}{}", c.name, opts, hex(c.payload));
                for y in 0..m.height() {
                    let row: String = (0..m.width()).map(|x| if m.get(x, y) { '1' } else { '0' }).collect();
                    println!("{row}");
                }
                println!("end");
            }
            Ok(Encoded::Stacked(s)) => {
                println!("case {} {}{}", c.name, opts, hex(c.payload));
                for row in &s.rows {
                    let mut line = String::new();
                    for (i, &w) in row.bars.iter().enumerate() {
                        line.extend(std::iter::repeat_n(if i % 2 == 0 { '1' } else { '0' }, usize::from(w)));
                    }
                    println!("{line}");
                }
                println!("end");
            }
            Ok(other) => eprintln!("skip {} {}: unexpected {other:?}", c.name, c.payload),
            Err(e) => eprintln!("skip {} {}: {e}", c.name, c.payload),
        }
    }
}
