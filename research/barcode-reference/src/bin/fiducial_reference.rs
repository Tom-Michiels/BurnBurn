//! Writes `crates/burnburn-generators/tests/fixtures/fiducial-reference.txt` to stdout: two
//! independent sources for the fiducial tests.
//!
//! 1. The official AprilTag C sources (`tag16h5.c`, `tag25h9.c`, `tag36h10.c`, `tag36h11.c`, BSD-2-Clause,
//!    vendored in the crate `apriltag-sys` 0.4.0): code words and bit positions. The tests re-draw each tag
//!    with the algorithm of `apriltag_to_image` (bit set = white).
//! 2. `data/dictionaries/dict_7x7_100.json` of the crate `locus-core` 0.10.0 (provenance field:
//!    `cv2.aruco.DICT_7X7_100`): the first 100 OpenCV 7x7 codes, in OpenCV polarity (bit set = white).
//!
//! Run: `cargo run --bin fiducial_reference -- <apriltag-src dir> <locus-core dictionaries dir> > .../fiducial-reference.txt`

use std::{env, fs, path::Path, process};

fn between<'a>(text: &'a str, from: &str, to: &str) -> &'a str {
    let a = text.find(from).unwrap_or_else(|| panic!("missing {from}")) + from.len();
    let b = text[a..].find(to).unwrap_or_else(|| panic!("missing {to}")) + a;
    &text[a..b]
}

fn number_after(text: &str, key: &str) -> usize {
    let a = text.find(key).unwrap_or_else(|| panic!("missing {key}")) + key.len();
    let rest = text[a..].trim_start();
    let end = rest.find(|c: char| !c.is_ascii_digit()).expect("end of number");
    rest[..end].parse().expect("number")
}

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: fiducial_reference <apriltag-src dir> <locus dictionaries dir>");
        process::exit(2);
    }
    println!(
        "# Reference data for the fiducial tests (generated by research/barcode-reference, bin fiducial_reference)."
    );
    println!("# Sources: official AprilTag C sources (apriltag-sys 0.4.0) and locus-core 0.10.0 dict_7x7_100.json.");
    for fam in ["16h5", "25h9", "36h10", "36h11"] {
        let c = fs::read_to_string(Path::new(&args[1]).join(format!("tag{fam}.c"))).expect("read tag file");
        let n = number_after(&c, "tf->nbits = ");
        let wab = number_after(&c, "tf->width_at_border = ");
        let total = number_after(&c, "tf->total_width = ");
        assert!(c.contains("tf->reversed_border = false;"), "{fam}: reversed border not expected");
        let mut bx = vec![0usize; n];
        let mut by = vec![0usize; n];
        for i in 0..n {
            bx[i] = number_after(&c, &format!("tf->bit_x[{i}] = "));
            by[i] = number_after(&c, &format!("tf->bit_y[{i}] = "));
        }
        let body = between(&c, "= {", "};");
        let codes: Vec<String> = body
            .split(',')
            .filter_map(|t| t.trim().strip_prefix("0x").map(|h| h.trim_end_matches("UL").to_string()))
            .map(|h| format!("{:x}", u64::from_str_radix(&h, 16).expect("hex")))
            .collect();
        assert_eq!(codes.len(), number_after(&c, "tf->ncodes = "), "{fam}: code count");
        println!("apriltag {fam} width_at_border={wab} total_width={total} nbits={n} codes={}", codes.len());
        println!("bit_x {}", bx.iter().map(usize::to_string).collect::<Vec<_>>().join(" "));
        println!("bit_y {}", by.iter().map(usize::to_string).collect::<Vec<_>>().join(" "));
        for chunk in codes.chunks(10) {
            println!("codes {}", chunk.join(" "));
        }
        println!("end");
    }
    let j = fs::read_to_string(Path::new(&args[2]).join("dict_7x7_100.json")).expect("read locus json");
    assert!(j.contains("cv2.aruco.DICT_7X7_100"), "provenance");
    let list = between(&j, "\"base_codes\": [", "]");
    let codes: Vec<String> =
        list.split(',').map(|t| t.trim().trim_matches('"').to_lowercase()).filter(|t| !t.is_empty()).collect();
    assert_eq!(codes.len(), 100);
    println!("opencv_7x7_100 payload_bits=49 polarity=bit-set-is-white");
    for chunk in codes.chunks(8) {
        println!("codes {}", chunk.join(" "));
    }
    println!("end");
}
