//! Built-in single-line (stroke) glyphs for engraving: digits, A–Z and a few signs.
//!
//! A BurnBurn-own set (no third-party data, so no licence question): polylines on a grid with
//! cap height 10 units and glyph width 6, advance 8. Rendered at cap height = 0.7 em. Strokes are
//! *open* paths; a stroke that returns to its start (O, 0, D) is still not a closed contour, so
//! nothing downstream fills it.

use burnburn_geometry::{Point, Segment, Subpath};

use crate::shape::TextError;

/// Characters the built-in stroke set can draw (space included).
pub const SINGLE_LINE_CHARS: &str = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-.+/:";

/// Grid units per em: cap height 10 units = 0.7 em.
/// Cap height of the stroke set as a fraction of the em.
pub(crate) const CAP_HEIGHT_EM: f64 = 0.7;
pub(crate) const UNITS_PER_EM: f64 = 10.0 / CAP_HEIGHT_EM;
/// Pen advance per character, in grid units.
pub(crate) const ADVANCE_UNITS: f64 = 8.0;

type Stroke = &'static [(f64, f64)];

