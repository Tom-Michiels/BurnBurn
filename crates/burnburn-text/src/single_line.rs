pub fn single_line_supports(ch: char) -> bool {
    strokes(ch).is_some()
}

/// Open stroke subpaths of `ch` with the grid origin at `origin` and `scale` mm per grid unit.
pub(crate) fn glyph_strokes(ch: char, origin: Point, scale: f64) -> Result<Vec<Subpath>, TextError> {
    let map = |(x, y): (f64, f64)| Point::new(origin.x + x * scale, origin.y + y * scale);
    let mut out = Vec::new();
    for stroke in strokes(ch).unwrap_or(&[]) {
        let Some((&first, rest)) = stroke.split_first() else { continue };
        let segments = rest.iter().map(|&p| Segment::Line { to: map(p) }).collect();
        out.push(Subpath::new(map(first), segments, false)?);
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_listed_character_has_strokes_within_the_grid() {
        for ch in SINGLE_LINE_CHARS.chars() {
            let s = strokes(ch).unwrap_or_else(|| panic!("{ch:?} listed but not defined"));
            for stroke in s {
                assert!(stroke.len() >= 2, "{ch:?}");
                assert!(stroke.iter().all(|&(x, y)| (0.0..=6.0).contains(&x) && (0.0..=10.0).contains(&y)), "{ch:?}");
            }
            assert_eq!(s.is_empty(), ch == ' ', "{ch:?}");
        }
        assert!(strokes('a').is_none() && strokes('é').is_none());
    }
}
